import { expect, it } from 'vitest'
import { puzzleDay } from './day'

it.each([
  ['2026-10-19T00:00:00Z', '2026-10-18'],
  ['2026-10-19T06:59:59.999Z', '2026-10-18'],
  ['2026-10-19T07:00:00Z', '2026-10-19'],
  ['2026-12-19T07:59:59.999Z', '2026-12-18'],
  ['2026-12-19T08:00:00Z', '2026-12-19'],
  ['2026-03-08T09:59:59Z', '2026-03-08'],
  ['2026-03-08T10:00:00Z', '2026-03-08'],
  ['2026-11-01T08:59:59Z', '2026-11-01'],
  ['2026-11-01T09:00:00Z', '2026-11-01'],
])('uses the Pacific calendar day at %s', (time, day) => {
  expect(puzzleDay(new Date(time))).toBe(day)
})
